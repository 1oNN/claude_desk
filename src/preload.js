const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('desk', {
  init: () => ipcRenderer.invoke('desk:init'),
  startSession: opts => ipcRenderer.invoke('desk:start', opts),
  resumeSession: id => ipcRenderer.invoke('desk:resume', id),
  stopSession: id => ipcRenderer.invoke('desk:stop', id),
  forgetSession: id => ipcRenderer.invoke('desk:forget', id),
  attach: (id, cols, rows) => ipcRenderer.invoke('desk:attach', id, cols, rows),
  write: (id, data) => ipcRenderer.send('desk:write', id, data),
  resize: (id, cols, rows) => ipcRenderer.send('desk:resize', id, cols, rows),
  say: (projectKey, text) => ipcRenderer.invoke('desk:say', projectKey, text),
  setUi: ui => ipcRenderer.send('desk:ui', ui),
  addProject: (machine, dir) => ipcRenderer.invoke('desk:addProject', machine, dir),
  laptopReconnect: () => ipcRenderer.invoke('desk:laptopReconnect'),
  memoryNow: () => ipcRenderer.invoke('desk:memoryNow'),
  log: s => ipcRenderer.send('desk:log', s),
  getSettings: () => ipcRenderer.invoke('desk:settings'),
  setSettings: patch => ipcRenderer.invoke('desk:setSettings', patch),
  pickPath: (what, defaultPath) => ipcRenderer.invoke('desk:pickPath', what, defaultPath),
  openPath: what => ipcRenderer.invoke('desk:openPath', what),
  accountAdd: o => ipcRenderer.invoke('desk:accountAdd', o),
  accountUpdate: (id, patch) => ipcRenderer.invoke('desk:accountUpdate', id, patch),
  accountRemove: id => ipcRenderer.invoke('desk:accountRemove', id),
  setupDone: () => ipcRenderer.invoke('desk:setupDone'),
  checkUpdate: () => ipcRenderer.invoke('desk:checkUpdate'),
  zoom: factor => ipcRenderer.send('desk:zoom', factor),
  clipRead: () => ipcRenderer.invoke('desk:clipRead'),
  clipWrite: text => ipcRenderer.send('desk:clipWrite', text),
  openUrl: url => ipcRenderer.send('desk:openUrl', url),
  devtools: () => ipcRenderer.send('desk:devtools'),
  newWindow: o => ipcRenderer.invoke('desk:newWindow', o),
  moveSession: (id, to) => ipcRenderer.invoke('desk:moveSession', id, to),
  focusWindow: wid => ipcRenderer.invoke('desk:focusWindow', wid),
  closeWindow: () => ipcRenderer.send('desk:closeWindow'),
  quit: () => ipcRenderer.send('desk:quit'),
  titleBar: o => ipcRenderer.send('desk:titleBar', o),
  fullScreen: () => ipcRenderer.send('desk:fullScreen'),
  newProject: name => ipcRenderer.invoke('desk:newProject', name),
  onSnapshot: cb => ipcRenderer.on('desk:snapshot', (_e, s) => cb(s)),
  onTick: cb => ipcRenderer.on('desk:tick', (_e, now) => cb(now)),
  onData: cb => ipcRenderer.on('desk:data', (_e, id, d) => cb(id, d)),
  onExit: cb => ipcRenderer.on('desk:exit', (_e, id, e) => cb(id, e)),
  onStarted: cb => ipcRenderer.on('desk:started', (_e, id) => cb(id)),
  onToast: cb => ipcRenderer.on('desk:toast', (_e, msg, kind) => cb(msg, kind)),
  onReleased: cb => ipcRenderer.on('desk:released', (_e, id, to) => cb(id, to)),
  onPlace: cb => ipcRenderer.on('desk:place', (_e, id) => cb(id)),
  onPrefs: cb => ipcRenderer.on('desk:prefs', (_e, prefs) => cb(prefs)),
});
